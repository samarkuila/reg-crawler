"""Mermaid ER diagram generated from the models, so docs/data-model.md cannot drift from the code.

python -m app.db.er            print the diagram
python -m app.db.er --write    refresh the diagram inside docs/data-model.md
"""

import sys
from pathlib import Path

from sqlalchemy import Column, MetaData, Table

from app.db.models import Base

DOC = Path(__file__).resolve().parents[2] / "docs" / "data-model.md"
START = "<!-- er:start (generated by python -m app.db.er --write; do not edit) -->"
END = "<!-- er:end -->"


def _type_name(column: Column) -> str:
    name = type(column.type.impl if hasattr(column.type, "impl") else column.type).__name__
    return {
        "String": "string",
        "Text": "text",
        "Integer": "int",
        "Boolean": "bool",
        "Date": "date",
        "DateTime": "datetime",
        "JSON": "json",
        "Enum": "enum",
    }.get(name, name.lower())


def _marks(table: Table, column: Column) -> str:
    marks = []
    if column.primary_key:
        marks.append("PK")
    if column.foreign_keys:
        marks.append("FK")
    unique = column.unique or any(
        len(c.columns) == 1 and column in c.columns.values()
        for c in table.constraints
        if c.__class__.__name__ == "UniqueConstraint"
    )
    if unique:
        marks.append("UK")
    return ",".join(marks)


def mermaid(metadata: MetaData | None = None) -> str:
    metadata = metadata or Base.metadata
    lines = ["erDiagram"]
    for table in sorted(metadata.tables.values(), key=lambda t: t.name):
        for column in table.columns:
            for fk in column.foreign_keys:
                parent = fk.column.table.name
                one = "|o" if column.nullable else "||"
                kind = "o|" if _marks(table, column).find("UK") >= 0 else "o{"
                edge = f"{parent.upper()} {one}--{kind} {table.name.upper()}"
                lines.append(f"  {edge} : {column.name}")
    for table in sorted(metadata.tables.values(), key=lambda t: t.name):
        lines.append(f"  {table.name.upper()} {{")
        for column in table.columns:
            marks = _marks(table, column)
            lines.append(f"    {_type_name(column)} {column.name}" + (f" {marks}" if marks else ""))
        lines.append("  }")
    return "\n".join(lines)


def write_doc(path: Path = DOC) -> None:
    text = path.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END)
    block = f"{START}\n```mermaid\n{mermaid()}\n```\n"
    path.write_text(text[:start] + block + text[end:], encoding="utf-8", newline="\n")


def current_block(path: Path = DOC) -> str:
    text = path.read_text(encoding="utf-8")
    return text[text.index(START) + len(START) : text.index(END)].strip()


if __name__ == "__main__":
    if "--write" in sys.argv:
        write_doc()
        print(f"Updated {DOC}")
    else:
        print(mermaid())
